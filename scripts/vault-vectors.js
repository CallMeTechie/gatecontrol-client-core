#!/usr/bin/env node
'use strict';

// Writes test/fixtures/vault-vectors.json: fixed inputs → the exact bytes vault-crypto produces. Android (and later
// the portal) check the same file, so every platform encrypts bit for bit alike. Only crypto_box_seal is random by
// design (an ephemeral key) — its vector is a sealed box to open. Run again only on purpose: a changed vector breaks
// every stored vault.
//
//   node scripts/vault-vectors.js

const fs = require('node:fs');
const path = require('node:path');
const vc = require('../src/utils/vault-crypto');

const hex = (b) => Buffer.from(b).toString('hex');
const seq = (start, n) => Uint8Array.from({ length: n }, (_, i) => (start + i) & 255);

(async () => {
  const sodium = await vc.ready();
  const kdf = { alg: 'argon2id', m: 19456, t: 2, p: 1, salt: vc.b64(seq(0x00, 16)) };
  const password = 'Korrekt Pferd Batterie Heftklammer – Grüße';
  const key = seq(0x80, 32);
  const nonce = seq(0x40, 24);
  const vaultId = 'Vt9bJm0n2QwErTyUiOpAsD';
  const itemId = 'It4kLm8Nq2RsTuVwXyZaBc';
  const item = '{"v":1,"type":"login","title":"Router","fields":{"username":"admin","password":"s3cr3t!","url":"http://192.168.1.1"}}';
  const seed = seq(0x20, 32);
  const pair = sodium.crypto_box_seed_keypair(seed);
  const rnd = {
    userKey: seq(0xa0, 32), recoveryKey: seq(0xc0, 32), keySeed: seed,
    personalId: 'Pv1aB2cD3eF4gH5iJ6kL7m', personalKey: seq(0xe0, 32),
    nonces: [seq(0x01, 24), seq(0x21, 24), seq(0x41, 24), seq(0x61, 24)],
  };
  const acc = vc.createAccount(password, 'Persönlich', { kdf, rnd });
  const file = path.join(__dirname, '..', 'test', 'fixtures', 'vault-vectors.json');
  // a sealed box is random: keep the one already pinned while it still opens
  const keepSealed = () => {
    try {
      const old = JSON.parse(fs.readFileSync(file, 'utf8')).sealed.sealed;
      return vc.openSealed(old, pair.publicKey, pair.privateKey) && old;
    } catch { return null; }
  };
  const out = {
    $comment: 'gatecontrol-vault crypto vectors (plugin README "Kryptoformat"). Bytes as hex, encrypted fields base64url without padding. Generated by scripts/vault-vectors.js — never change a vector.',
    libsodium: sodium.SODIUM_VERSION_STRING,
    masterKey: {
      password, passwordNfd: password.normalize('NFD'), kdf,
      key: hex(vc.masterKey(password, kdf)),
    },
    wrap: {
      key: hex(key), nonce: hex(nonce), ad: vc.AD.userKeyPw, plaintext: hex(seq(0xa0, 32)),
      wrapped: vc.b64(vc.wrap(key, seq(0xa0, 32), vc.AD.userKeyPw, nonce)),
    },
    name: {
      key: hex(key), nonce: hex(nonce), vaultId, name: 'Familie 👨‍👩‍👧',
      nameEnc: vc.encryptName(key, vaultId, 'Familie 👨‍👩‍👧', nonce),
    },
    item: {
      key: hex(key), nonce: hex(nonce), vaultId, itemId, rev: 3, json: item,
      blob: vc.encryptItemBytes(key, { vaultId, itemId, rev: 3 }, sodium.from_string(item), nonce),
    },
    recoveryKey: { key: hex(seq(0xc0, 32)), text: vc.formatRecoveryKey(seq(0xc0, 32)) },
    sealed: {
      seed: hex(seed), publicKey: hex(pair.publicKey), secretKey: hex(pair.privateKey),
      key: hex(key), sealed: keepSealed() || vc.sealKey(key, pair.publicKey),
    },
    safetyNumber: { publicKey: hex(pair.publicKey), text: vc.safetyNumber(pair.publicKey) },
    account: {
      password, kdf, personalName: 'Persönlich',
      rnd: { userKey: hex(rnd.userKey), recoveryKey: hex(rnd.recoveryKey), keySeed: hex(seed), personalId: rnd.personalId,
        personalKey: hex(rnd.personalKey), nonces: rnd.nonces.map(hex) },
      body: { ...acc.body, personal: { id: acc.body.personal.id, nameEnc: acc.body.personal.nameEnc } },
      recoveryKey: acc.recoveryKey,
    },
  };
  fs.writeFileSync(file, JSON.stringify(out, null, 2) + '\n');
  console.log('wrote', path.relative(process.cwd(), file));
})();
